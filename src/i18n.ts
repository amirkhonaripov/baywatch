export const DICTS: Record<Lang, Dict> = { en, ru, uz };

export type TFn = (key: Key, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): TFn {
  const d = DICTS[lang] || en;
  return (key, vars) => {
    let s = d[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

/** Typed lookup for keys built at runtime (e.g. `ev.${type}`); falls back to the raw value. */
export function tk(t: TFn, prefix: string, value: string | undefined | null): string {
  if (!value) return "";
  const key = `${prefix}.${value}` as Key;
  return key in en ? t(key) : value;
}
